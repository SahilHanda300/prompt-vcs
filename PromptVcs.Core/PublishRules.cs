using System.Text;
using System.Text.Json;
using DiffPlex;
using DiffPlex.DiffBuilder;
using DiffPlex.DiffBuilder.Model;

namespace PromptVcs.Core;

public record PublishOutcome(bool Ok, int BuildVersion, string? ArtifactRelativePath, string? Detail);

/// <summary>
/// Owns the first-run vs. diff-aware-update decision — the core of what the
/// publish stage is responsible for, per design: it doesn't just pass the
/// prompt through to the generator, it decides how to build/update the site.
///
/// Runs in-process as part of Pipeline now (previously a separate MCP server
/// call from the CLI). Prior-build lookup comes directly from the PromptRecord
/// it's given — no separate build-metadata store to keep in sync, since the
/// whole pipeline (store, QA, publish) runs in one process against one Store.
/// </summary>
public class PublishRules
{
    private readonly IClaudeCodeInvoker _invoker;
    private readonly string _siteRootDir;

    public PublishRules(IClaudeCodeInvoker invoker, string siteRootDir)
    {
        _invoker = invoker;
        _siteRootDir = siteRootDir;
    }

    /// Update path only (Pipeline calls this when a prior successful build
    /// exists) — one Claude Code call, diff-aware.
    public async Task<PublishOutcome> PublishAsync(PromptRecord record, int promptVersion, string content, IReadOnlyList<Attachment>? attachments = null)
    {
        var buildVersion = record.Builds.Count + 1;
        var previousBuild = record.Builds.LastOrDefault(b => b.Status == BuildStatus.Success);
        var previousContent = previousBuild != null
            ? record.History.FirstOrDefault(h => h.Version == previousBuild.PromptVersion)?.Content
            : null;

        var previousArtifactPath = Path.Combine(_siteRootDir, record.Id, "index.html");
        var previousArtifact = previousBuild != null && File.Exists(previousArtifactPath)
            ? await File.ReadAllTextAsync(previousArtifactPath)
            : null;

        var generationPrompt = previousContent == null || previousArtifact == null
            ? BuildFirstRunPrompt(record.Name, content)
            : BuildUpdatePrompt(record.Name, previousContent, content, previousArtifact);

        var claudeResult = await _invoker.InvokeAsync(generationPrompt, attachments);
        if (!claudeResult.Ok)
        {
            return new PublishOutcome(false, buildVersion, null, claudeResult.Detail);
        }

        return await FinalizeArtifactAsync(record, buildVersion, claudeResult.Text);
    }

    /// First-run path only (Pipeline calls this when there is no prior
    /// successful build). A short screening-and-planning call decides
    /// safe/feasible plus (for a content site) a shared design brief and a
    /// section breakdown; for a content site, each section is then
    /// generated by its own Claude Code call running IN PARALLEL and
    /// assembled here — wall-clock time is roughly the slowest single
    /// section, not the sum of all of them, since real measurement showed
    /// a one-shot full-page call takes 25-55s dominated purely by output
    /// token count (confirmed via duration_api_ms ≈ duration_ms with
    /// num_turns=1 — i.e. no removable agentic overhead, just generation
    /// time proportional to output size). Splitting into N independently
    /// generated sections cuts that to roughly 1/N, without shrinking the
    /// total content/quality the way capping output length would.
    ///
    /// Deliberately NOT used for an "app"-type prompt (a calculator, a
    /// todo list, etc.) — those are usually one cohesive JS state machine
    /// where markup and logic are tightly coupled, and splitting that
    /// safely across independent calls is a materially harder problem than
    /// independent content sections; the plan step itself decides
    /// content-vs-app and an app falls back to the single full-page call
    /// (BuildFirstRunPrompt, same as before this change — still the
    /// original 25-55s latency for that case). Also NOT used for edits —
    /// BuildUpdatePrompt needs the diff + full previous artifact as
    /// context; parallel-updating a sectioned artifact is a real follow-up,
    /// not done here.
    public async Task<(QaCheckResult Safety, QaCheckResult Feasibility, PublishOutcome Outcome)> ScreenAndPublishFirstRunAsync(
        PromptRecord record, int promptVersion, string content, IReadOnlyList<Attachment>? attachments = null)
    {
        var buildVersion = record.Builds.Count + 1;
        // Uses opus, per explicit request, trading away haiku's measured
        // ~2x latency advantage for this call shape (see CLAUDE.md) for
        // whatever extra judgment quality opus brings — note the real
        // regressions found in testing (brand-name drift, dropped
        // instructions, flat section tones) were structural/prompt-design
        // issues independent of model choice, already fixed separately via
        // the shared-name check, external-resource guard, and tone
        // alternation below; this swap is an additional quality margin on
        // top of those fixes, not a fix for them by itself. Still
        // deliberately asks for ONLY the screening judgment, not a design
        // brief or section plan —
        // screening judgment now, not a design brief or section plan — an
        // earlier version had the model invent those too, which meant this
        // call's own output size (and so its latency) scaled with how much
        // creative content it decided to describe. Design brief and section
        // breakdown are now fixed/code-chosen (see PickDesignBrief and
        // ContentSectionTemplate below) instead of model-decided, trading a
        // little per-build design variety for a call that's consistently
        // close to the ~4-6s floor measured for this environment.
        var screenResult = await _invoker.InvokeAsync(BuildFirstRunScreenPrompt(record.Name, content), model: "opus");
        if (!screenResult.Ok)
        {
            var failure = new QaCheckResult(false, screenResult.Detail ?? "Screening call failed to run.");
            return (failure, failure, new PublishOutcome(false, buildVersion, null, screenResult.Detail));
        }

        ScreenResult screen;
        try
        {
            var text = screenResult.Text;
            var start = text.IndexOf('{');
            var end = text.LastIndexOf('}');
            var jsonText = start >= 0 && end > start ? text[start..(end + 1)] : text;
            screen = JsonSerializer.Deserialize<ScreenResult>(jsonText, PlanJsonOptions)
                ?? throw new JsonException("null screen result");
            screen = screen with { Name = string.IsNullOrWhiteSpace(screen.Name) ? record.Name : screen.Name };
        }
        catch (JsonException)
        {
            var failure = new QaCheckResult(false, $"Could not parse screening response: {screenResult.Text.Trim()}");
            return (failure, failure, new PublishOutcome(false, buildVersion, null, "Screening response unparseable."));
        }

        var safetyResult = new QaCheckResult(screen.Safe, screen.SafetyReason);
        var feasibilityResult = new QaCheckResult(screen.Feasible, screen.FeasibilitySummary);

        if (!screen.Safe || !screen.Feasible)
        {
            return (safetyResult, feasibilityResult, new PublishOutcome(false, buildVersion, null, "Skipped: did not pass screening."));
        }

        // App-type: fall back to the original single full-page call,
        // unchanged — see the class-level doc comment for why apps aren't
        // split into parallel sections.
        if (screen.Type != "content")
        {
            var fallbackResult = await _invoker.InvokeAsync(BuildFirstRunPrompt(record.Name, content), attachments);
            if (!fallbackResult.Ok)
            {
                return (safetyResult, feasibilityResult, new PublishOutcome(false, buildVersion, null, fallbackResult.Detail));
            }
            var fallbackOutcome = await FinalizeArtifactAsync(record, buildVersion, fallbackResult.Text);
            return (safetyResult, feasibilityResult, fallbackOutcome);
        }

        var designBrief = PickDesignBrief(content);
        // opus here too, same trade as the screening call above.
        var sectionTasks = ContentSectionTemplate
            .Select(s => _invoker.InvokeAsync(BuildSectionPrompt(screen.Name!, content, designBrief, s.Id, s.Role, s.Tone), attachments, model: "opus"))
            .ToList();
        var sectionResults = await Task.WhenAll(sectionTasks);

        var failedSections = sectionResults
            .Select((r, i) => (Result: r, Section: ContentSectionTemplate[i]))
            .Where(x => !x.Result.Ok)
            .ToList();
        if (failedSections.Count > 0)
        {
            var detail = $"Section(s) failed to generate: {string.Join(", ", failedSections.Select(f => $"{f.Section.Id} ({f.Result.Detail})"))}";
            return (safetyResult, feasibilityResult, new PublishOutcome(false, buildVersion, null, detail));
        }

        // Real bug, found by reading actual output rather than trusting the
        // prompt instruction: sections generated independently each
        // invented their OWN brand name when one wasn't enforced, producing
        // a page with 2-3 different names on it. The shared `screen.Name`
        // instruction fixed this in testing, but a prompt instruction is a
        // request the model can still get wrong on some other run — this is
        // a deterministic check that catches it instead of silently
        // publishing an inconsistent page. The hero section's whole role is
        // "introduce the subject by name" (see ContentSectionTemplate), so
        // its absence there specifically is the clearest signal something
        // went wrong, not just a coincidence of phrasing.
        var heroIndex = Array.FindIndex(ContentSectionTemplate, s => s.Id == "hero");
        var heroText = System.Net.WebUtility.HtmlDecode(sectionResults[heroIndex].Text);
        if (!heroText.Contains(screen.Name!, StringComparison.OrdinalIgnoreCase))
        {
            return (safetyResult, feasibilityResult, new PublishOutcome(
                false, buildVersion, null,
                $"Hero section didn't include the shared name \"{screen.Name}\" — sections may be visually inconsistent, failing rather than publishing a mismatched page."));
        }

        var assembledHtml = string.Join("\n",
            "<!doctype html>",
            "<html lang=\"en\">",
            "<head>",
            "<meta charset=\"utf-8\">",
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">",
            $"<title>{System.Net.WebUtility.HtmlEncode(screen.Name!)}</title>",
            "</head>",
            "<body>",
            string.Join("\n", sectionResults.Select(r => r.Text.Trim())),
            "</body>",
            "</html>");

        var outcome = await FinalizeArtifactAsync(record, buildVersion, assembledHtml);
        return (safetyResult, feasibilityResult, outcome);
    }

    private static readonly JsonSerializerOptions PlanJsonOptions = new() { PropertyNameCaseInsensitive = true };

    private record ScreenResult(bool Safe, string? SafetyReason, bool Feasible, string? FeasibilitySummary, string Type, string? Name);

    private record ContentSection(string Id, string Role, string Tone);

    /// Always these 4 roles, in this order, for every parallel-generated
    /// content-type first run — fixed rather than model-decided, so the
    /// screening call above doesn't have to spend output tokens (and
    /// therefore time) inventing a section breakdown. Each section call
    /// still gets the full original prompt, so it can fill in subject-
    /// specific content for its role on its own.
    ///
    /// Tone alternates dark/light/dark/light by fixed position, found
    /// necessary by actually reading generated pages, not just checking
    /// they built: without it, independently-generated sections have no way
    /// to know what lightness their neighbors picked, and in practice often
    /// converged on the same "safe" dark (or light) variant of the shared
    /// palette — multiple real generated pages came out as a visually flat
    /// wall of 3-4 adjacent sections in near-identical colors, which a
    /// single-call generation would never produce (one pass naturally
    /// alternates for rhythm). Fixing this at the role level, not leaving it
    /// to each section to guess, guarantees adjacent-section contrast by
    /// construction.
    private static readonly ContentSection[] ContentSectionTemplate =
    {
        new("hero", "An inviting header/hero introducing the subject by name, with a short tagline and a clear call-to-action.", "dark"),
        new("highlights", "The key features, offerings, menu items, services, or highlights relevant to the subject.", "light"),
        new("details", "Supporting detail — the subject's story, background, social proof, or testimonials, whichever fits best.", "dark"),
        new("footer", "A footer with contact info, hours, or location as relevant, and a final call-to-action.", "light"),
    };

    /// A small curated set of concrete, pre-written design briefs rather
    /// than asking Claude to invent one — removes that decision (and its
    /// output tokens) from the latency-critical screening call. Picked
    /// deterministically per prompt (not randomly) so re-running the exact
    /// same prompt text lands on the same brief.
    private static readonly string[] DesignBriefs =
    {
        "Warm earthy palette (deep browns, cream, terracotta accent), serif display headings, clean sans-serif body text, generous spacing, cozy artisanal tone.",
        "Cool modern palette (deep navy, white, a single vivid accent like teal or coral), bold geometric sans-serif headings, confident and minimal, tight spacing.",
        "Soft pastel palette (blush, sage, cream), rounded friendly sans-serif typography throughout, airy generous whitespace, approachable and calm tone.",
        "High-contrast monochrome (near-black, white, one sharp accent color), condensed bold headings, editorial/magazine feel, crisp structured grid.",
        "Nature-inspired palette (forest green, warm beige, soft gold accent), classic serif headings paired with humanist sans-serif body, organic and grounded tone.",
        "Vibrant energetic palette (deep purple, electric accent color, white), rounded modern sans-serif throughout, playful and bold, dynamic spacing.",
    };

    private static string PickDesignBrief(string content)
    {
        // string.GetHashCode() is randomized per process in .NET (security
        // feature) — not stable across runs, so a simple stable sum is used
        // instead to keep the "same prompt text -> same brief" property real.
        var sum = content.Aggregate(0, (acc, c) => unchecked(acc + c));
        return DesignBriefs[sum % DesignBriefs.Length];
    }

    private async Task<PublishOutcome> FinalizeArtifactAsync(PromptRecord record, int buildVersion, string rawHtml)
    {
        var sanitized = ArtifactSanitizer.Sanitize(rawHtml);
        if (!sanitized.Ok)
        {
            return new PublishOutcome(false, buildVersion, null, sanitized.Detail);
        }

        var siteDir = Path.Combine(_siteRootDir, record.Id);
        var versionedDir = Path.Combine(siteDir, $"v{buildVersion}");
        Directory.CreateDirectory(versionedDir);
        var utf8NoBom = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false);
        await File.WriteAllTextAsync(Path.Combine(versionedDir, "index.html"), sanitized.Html, utf8NoBom);
        await File.WriteAllTextAsync(Path.Combine(siteDir, "index.html"), sanitized.Html, utf8NoBom);

        // Points at this build's own versioned copy, not the shared
        // "latest" copy at /site/{id}/ — otherwise every build's link in
        // build history would show whatever is currently live instead of
        // what that specific build actually produced.
        return new PublishOutcome(true, buildVersion, $"/site/{record.Id}/v{buildVersion}/", null);
    }

    private static string BuildFirstRunPrompt(string promptName, string content)
    {
        return string.Join("\n", new[]
        {
            "You are generating a complete, self-contained, single-file HTML artifact for a tool called PromptVCS.",
            "The people using this tool are non-technical and often describe what they want in just a few words. Treat brevity as creative freedom, not missing information — never ask for more detail, and never output something sparse, generic, or placeholder-looking.",
            "The output may be a content site or a fully functional interactive app (infer which from the prompt) — infer this yourself, do not ask.",
            "",
            "Quality bar, non-negotiable regardless of how short or vague the prompt is:",
        }
        .Concat(QualityBarLines())
        .Concat(new[]
        {
            "",
            "Requirements: a single HTML file with any needed CSS/JS inlined, no external dependencies (no CDNs, no external fonts or image URLs/files) — a provided attachment's placeholder token is the one exception, since it's resolved to an embedded image, not an external resource. Include a viewport meta tag and a descriptive <title> tag.",
            "Respond with ONLY the HTML document — no explanation, no markdown code fences.",
            "",
            $"Prompt name: {promptName}",
            "Prompt:",
            content,
        }));
    }

    /// Short, fast call: ONLY screening (safe/feasible + content-vs-app).
    /// Deliberately asks for nothing else — no design brief, no section
    /// plan — so this call's output stays tiny and its latency stays close
    /// to the ~4-6s floor measured for a minimal call in this environment,
    /// rather than scaling with how much creative content the model decides
    /// to describe up front.
    private static string BuildFirstRunScreenPrompt(string promptName, string content)
    {
        return string.Join("\n",
            "You are screening a prompt for a tool called PromptVCS. Just the screening judgment — do not generate or describe any content, design, or layout.",
            "The people using this tool are non-technical and often describe what they want in just a few words. Treat brevity as creative freedom, not missing information — never ask for more detail, and this is not a reason to fail either check below.",
            "",
            "Assess:",
            "1. safe — is it free of genuinely unsafe/harmful content? Being brief or vague is not unsafe.",
            "2. feasible — can something reasonable be built from it as a single self-contained HTML page? Mark true unless the prompt is empty/gibberish, or explicitly requires something a single page structurally cannot provide (e.g. a real multi-user backend, a database, server-side payments).",
            "3. type — ONLY if safe and feasible: \"content\" for a content/marketing-style site (landing page, portfolio, informational site, storefront listing, etc.), or \"app\" for a tool with real interactive state/logic (a calculator, a todo list, a game, a converter, etc. — anything where UI and JS logic are too tightly coupled to generate in independent pieces). If not safe/feasible, type can be anything.",
            "4. name — ONLY if safe and feasible and type is \"content\": a short, specific brand/subject name (2-4 words) for this page. If the prompt already names one, use that exactly; if not, invent ONE plausible name. This exact name will be handed to several independent calls that generate the page's sections, so they stay consistent with each other instead of each inventing a different name — do not skip this or leave it generic.",
            "",
            "Respond with ONLY a single-line JSON object, nothing else:",
            "{\"safe\": boolean, \"safetyReason\": short string, \"feasible\": boolean, \"feasibilitySummary\": short string, \"type\": \"content\"|\"app\", \"name\": short string}",
            "Keep safetyReason and feasibilitySummary each to one short sentence.",
            "",
            $"Prompt name: {promptName}",
            "Prompt:",
            content);
    }

    /// One content section of a parallel-generated first-run page (see
    /// ScreenAndPublishFirstRunAsync) — several of these run concurrently
    /// against the same shared designBrief so they read as one cohesive
    /// page despite being generated independently. Uses a trimmed,
    /// section-specific quality bar rather than the full QualityBarLines()
    /// (shared with the full-page prompts) — several of those bullets (app
    /// JS functionality, calculator-specific input handling) don't apply to
    /// an individual content section and only added irrelevant instructions
    /// for the model to read and reason about.
    private static string BuildSectionPrompt(string sharedName, string content, string designBrief, string sectionId, string sectionRole, string tone)
    {
        var toneInstruction = tone == "dark"
            ? "This section must use the DARKEST, most saturated/deep color(s) from the shared design brief's own palette as its primary background (stay within that palette — don't jump to pure black if the brief doesn't call for it)."
            : "This section must use the LIGHTEST, most pale/airy color(s) from the shared design brief's own palette as its primary background (stay within that palette — don't jump to pure white if the brief doesn't call for it).";
        return string.Join("\n", new[]
        {
            "You are generating ONE section of a larger self-contained HTML page for a tool called PromptVCS. Several other sections are being generated in parallel by separate calls like this one — you will not see their output, so strict adherence to the shared design brief, shared name, and this section's assigned background weight below is the only thing keeping the final page consistent and visually rhythmic rather than flat.",
            $"Shared brand/subject name — use this EXACT name wherever the page names itself (e.g. in a logo/heading/footer), do not invent or use a different name: {sharedName}",
            $"Shared design brief — follow exactly, do not deviate or reinterpret: {designBrief}",
            $"Assigned background weight for THIS section (important — this is how sections stay visually distinct from their neighbors despite being generated independently): {toneInstruction}",
            $"This call's section: \"{sectionId}\" — {sectionRole}",
            "",
            "Quality bar for this section:",
            "- Make confident, specific creative decisions for everything else (copy, details, offerings) that fits the overall prompt and the shared name above. Never use placeholder text like 'Lorem ipsum', '[Your text here]', or similar.",
            "- Genuinely polished: readable typography, sensible spacing, fits the shared design brief exactly.",
            "- Fully responsive at phone width and up.",
            "- No external dependencies: no CDN links, no external font imports (e.g. no @import/<link> to fonts.googleapis.com or similar), no external image URLs. Use system/web-safe font stacks only. A provided attachment's placeholder token (if any, and if this section is where it belongs — e.g. a logo in a header) is the one exception, since it's resolved to an embedded image, not an external resource.",
            "- Keep this one section lean and efficient — roughly 60-120 words of visible copy and compact, non-repetitive CSS (reuse one class per logical element, don't over-decorate with extra wrapper divs or redundant rules). This is ONE part of a multi-section page, not the whole page: being concise here is correct, not a quality compromise — the page's overall polish comes from several well-made concise sections together, not from any single section being exhaustive.",
            "",
            "Respond with ONLY a single HTML fragment for this section — a <header>, <section>, or <footer> element as appropriate (no <html>/<head>/<body>, no markdown code fences, no explanation). Any CSS this section needs goes in its own <style> block scoped under a unique class name for this section, so it can't collide with other sections' styles. Any JS this section needs (e.g. a mobile nav toggle) goes in its own <script> block, using only ids/classes scoped to this section. A provided attachment's placeholder token (if any, and if this section is where it belongs) is used verbatim as an <img src=\"...\">.",
            "",
            "Overall prompt (for tone/content fit — this section is only PART of the full page):",
            content,
        });
    }

    /// Shared between BuildFirstRunPrompt and BuildSectionPrompt
    private static IEnumerable<string> QualityBarLines() => new[]
    {
        "- Make confident, specific creative decisions to fill in anything unstated: invent a plausible name/brand, tagline, and realistic body copy that fits the theme. Never use placeholder text like 'Lorem ipsum', '[Your text here]', 'Company Name', or similar.",
        "- Produce a genuinely polished visual design: a cohesive modern color palette, readable typography with a clear hierarchy, sensible spacing, and multiple relevant sections — not a single heading and a paragraph.",
        "- If the prompt describes an app or tool (a calculator, a todo list, a converter, a game, etc.), implement REAL working functionality in JavaScript — actual computation, state, and interactivity. Never ship a static mockup or a button that does nothing.",
        "- Handle the range of input a real (non-technical) person would reasonably type, not just the narrowest valid case. For example, a calculator should accept natural notation like implicit multiplication ('8cos(6)', '2(3+4)', '3π') rather than showing a bare error for it; a form should tolerate minor formatting variation. Only show an error for genuinely invalid input, and make it specific, not just the word 'Error'.",
        "- Fully responsive at phone width and up.",
    };

    private static string BuildUpdatePrompt(string promptName, string previousContent, string newContent, string previousArtifact)
    {
        var diffBuilder = new InlineDiffBuilder(new Differ());
        var diffResult = diffBuilder.BuildDiffModel(previousContent, newContent);
        var diffText = string.Join("\n", diffResult.Lines.Select(FormatDiffLine));

        return string.Join("\n",
            "You are updating an existing self-contained, single-file HTML artifact for a tool called PromptVCS, used by non-technical people.",
            "The prompt that generated it has changed. Below is a line diff of the prompt change (+ added, - removed) and the existing artifact.",
            "Apply a targeted update reflecting the diff — do not regenerate from scratch unless the diff requires it.",
            "Keep (or improve) the same quality bar as the original: no placeholder-looking text, a polished cohesive design, and real working functionality for anything interactive — never let an update make the result feel sparser or less finished than before.",
            "If the diff references an attached image (e.g. a logo) and you were given its placeholder token above, actually add an <img> using that exact placeholder token as its src in the appropriate place — don't just mention it in passing.",
            "Respond with ONLY the complete updated HTML document — no explanation, no markdown code fences.",
            "",
            $"Prompt name: {promptName}",
            "Prompt diff:",
            diffText,
            "",
            "Existing artifact:",
            previousArtifact);
    }

    private static string FormatDiffLine(DiffPiece line) => line.Type switch
    {
        ChangeType.Inserted => $"+ {line.Text}",
        ChangeType.Deleted => $"- {line.Text}",
        _ => $"  {line.Text}",
    };
}
